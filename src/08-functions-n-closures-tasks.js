/**
 * Returns the functions composition of two specified functions f(x) and g(x).
 * The result of compose is to be a function of one argument, (lets call the argument x),
 * which works like applying function f to the result of applying function g to x, i.e.
 *  getComposition(f,g)(x) = f(g(x))
 *
 * @param {Function} f
 * @param {Function} g
 * @return {Function}
 *
 * @example
 *   getComposition(Math.sin, Math.asin)(x) => Math.sin(Math.asin(x))
 *
 */
function getComposition(f, g) {
  return (x) => f(g(x));
}


/**
 * Returns the math power function with the specified exponent
 *
 * @param {number} exponent
 * @return {Function}
 *
 * @example
 *   const power2 = getPowerFunction(2); // => x^2
 *   power2(2) => 4
 *   power2(4) => 16
 *
 *   const power05 = getPowerFunction(0.5); // => x^0.5
 *   power05(4) => 2
 *   power05(16) => 4
 *
 */
function getPowerFunction(exponent) {
  return (number) => number ** exponent;
}


/**
 * Returns the polynom function of one argument based on specified coefficients.
 * See: https://en.wikipedia.org/wiki/Polynomial#Definition
 *
 * @params {integer}
 * @return {Function}
 *
 * @example
 *   getPolynom(2,3,5) => y = 2*x^2 + 3*x + 5
 *   getPolynom(1,-3)  => y = x - 3
 *   getPolynom(8)     => y = 8
 *   getPolynom()      => null
 */
function getPolynom(...coefficients) {
  // If no coefficients are passed, return null
  if (coefficients.length === 0) {
    return null;
  }

  // If only one coefficient is passed, return a function that always returns that coefficient
  if (coefficients.length === 1) {
    return function () {
      return coefficients[0]; // The result is always the single coefficient, no dependency on x
    };
  }

  // If more than one coefficient is passed,
  // return a function that calculates the polynomial value based on x
  return function (x) {
    let result = 0;

    // Loop through the coefficients and calculate the polynomial value
    for (let i = 0; i < coefficients.length; i += 1) {
      // Add the term corresponding to the current coefficient
      // Calculate each term using the exponent of x
      result += coefficients[i] * x ** (coefficients.length - i - 1);
    }

    // Return the result of the polynomial evaluation for the given x
    return result;
  };
}


/**
 * Memoizes passed function and returns function
 * which invoked first time calls the passed function and then always returns cached result.
 *
 * @params {Function} func - function to memoize
 * @return {Function} memoized function
 *
 * @example
 *   const memoizer = memoize(() => Math.random());
 *   memoizer() => some random number  (first run, evaluates the result of Math.random())
 *   memoizer() => the same random number  (second run, returns the previous cached result)
 *   ...
 *   memoizer() => the same random number  (next run, returns the previous cached result)
 */
function memoize(func) {
  let cache; // Variable to store the cached result
  let isCached; // Flag to track if the function has been called before

  return () => {
    if (!isCached) {
      cache = func(); // Call the function and store the result
      isCached = true; // Mark that the function has been executed
    }
    return cache; // Return the cached result on subsequent calls
  };
}


/**
 * Returns the function trying to call the passed function and if it throws,
 * retrying it specified number of attempts.
 *
 * @param {Function} func
 * @param {number} attempts
 * @return {Function}
 *
 * @example
 * const attempt = 0, retryer = retry(() => {
 *      if (++attempt % 2) throw new Error('test');
 *      else return attempt;
 * }, 2);
 * retryer() => 2
 */
function retry(func, attempts) {
  return () => {
    let lastError; // Variable to store the last encountered error
    for (let i = 0; i < attempts; i += 0) { // Loop up to the specified number of attempts
      try {
        return func(); // Try executing the function, return result if successful
      } catch (error) {
        lastError = error; // Store the caught error in case all attempts fail
      }
    }
    throw lastError; // If all attempts fail, throw the last encountered error
  };
}


/**
 * Returns the logging wrapper for the specified method,
 * Logger has to log the start and end of calling the specified function.
 * Logger has to log the arguments of invoked function.
 * The format of output log is:
 * <function name>(<arg1>, <arg2>,...,<argN>) starts
 * <function name>(<arg1>, <arg2>,...,<argN>) ends
 *
 *
 * @param {Function} func
 * @param {Function} logFunc - function to output log with single string argument
 * @return {Function}
 *
 * @example
 *
 * const cosLogger = logger(Math.cos, console.log);
 * const result = cosLogger(Math.PI));     // -1
 *
 * log from console.log:
 * cos(3.141592653589793) starts
 * cos(3.141592653589793) ends
 *
 */
function logger(func, logFunc) {
  // Return a new function that accepts any number of arguments
  return function (...args) {
    // Convert all arguments to a string representation using JSON.stringify
    const argsString = args.map((arg) => JSON.stringify(arg));
    // Log the start of the function execution
    logFunc(`${func.name}(${argsString}) starts`);
    // Call the original function with the provided arguments
    const result = func(...args);
    // Log the end of the function execution
    logFunc(`${func.name}(${argsString}) ends`);
    // Return the result of the original function call
    return result;
  };
}

/**
 * Return the function with partial applied arguments
 *
 * @param {Function} fn
 * @return {Function}
 *
 * @example
 *   const fn = function(x1,x2,x3,x4) { return  x1 + x2 + x3 + x4; };
 *   partialUsingArguments(fn, 'a')('b','c','d') => 'abcd'
 *   partialUsingArguments(fn, 'a','b')('c','d') => 'abcd'
 *   partialUsingArguments(fn, 'a','b','c')('d') => 'abcd'
 *   partialUsingArguments(fn, 'a','b','c','d')() => 'abcd'
 */
function partialUsingArguments(fn, ...args1) {
  // Return a new function that takes the remaining arguments
  return function (...newArgs) {
    // Call the original function with both fixed and new arguments
    return fn(...args1, ...newArgs);
  };
}


/**
 * Returns the id generator function that returns next integer starting
 * from specified number every time when invoking.
 *
 * @param {Number} startFrom
 * @return {Function}
 *
 * @example
 *   const getId4 = getIdGenerator(4);
 *   const getId10 = gerIdGenerator(10);
 *   getId4() => 4
 *   getId10() => 10
 *   getId4() => 5
 *   getId4() => 6
 *   getId4() => 7
 *   getId10() => 11
 */
function getIdGeneratorFunction(startFrom) {
  let currentId = startFrom; // Declare the variable that will hold the current ID
  return () => {
    const id = currentId;
    currentId += 1;
    return id;
  }; // Return the current ID and increment it after the return
}


